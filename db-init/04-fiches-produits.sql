-- Fiche technique de chaque produit : une table très large (une quarantaine de colonnes), plus large que l'écran,
-- pour voir les tableaux défiler sur place dans la liste, la structure et le formulaire d'édition.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS fiches_produits (
  produit_id INT PRIMARY KEY,
  sku VARCHAR(20) NOT NULL UNIQUE,
  ean CHAR(13) DEFAULT NULL,
  marque VARCHAR(60) NOT NULL,
  collection VARCHAR(60) DEFAULT NULL,
  saison ENUM('printemps','été','automne','hiver','toute l''année') NOT NULL DEFAULT 'toute l''année',
  couleur_principale VARCHAR(30) DEFAULT NULL,
  couleur_secondaire VARCHAR(30) DEFAULT NULL,
  matiere VARCHAR(60) DEFAULT NULL,
  taille ENUM('XS','S','M','L','XL','unique') NOT NULL DEFAULT 'unique',
  longueur_cm DECIMAL(5,1) DEFAULT NULL,
  largeur_cm DECIMAL(5,1) DEFAULT NULL,
  hauteur_cm DECIMAL(5,1) DEFAULT NULL,
  poids_g INT DEFAULT NULL,
  poids_emballe_g INT DEFAULT NULL,
  pays_fabrication CHAR(2) DEFAULT NULL,
  age_minimum TINYINT DEFAULT NULL,
  norme_ce TINYINT(1) NOT NULL DEFAULT 0,
  lavable TINYINT(1) NOT NULL DEFAULT 0,
  allergenes VARCHAR(120) DEFAULT NULL,
  dlc_jours SMALLINT DEFAULT NULL,
  prix_achat DECIMAL(8,2) NOT NULL,
  prix_conseille DECIMAL(8,2) NOT NULL,
  taux_tva DECIMAL(4,2) NOT NULL DEFAULT 20.00,
  marge_pct DECIMAL(5,2) DEFAULT NULL,
  delai_reappro_jours SMALLINT DEFAULT NULL,
  stock_minimum INT NOT NULL DEFAULT 0,
  emplacement VARCHAR(20) DEFAULT NULL,
  mot_cle_1 VARCHAR(30) DEFAULT NULL,
  mot_cle_2 VARCHAR(30) DEFAULT NULL,
  mot_cle_3 VARCHAR(30) DEFAULT NULL,
  note_moyenne DECIMAL(2,1) DEFAULT NULL,
  nb_avis INT NOT NULL DEFAULT 0,
  mis_en_avant TINYINT(1) NOT NULL DEFAULT 0,
  edition_limitee TINYINT(1) NOT NULL DEFAULT 0,
  lance_le DATE DEFAULT NULL,
  fin_de_vente_le DATE DEFAULT NULL,
  maj_le DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (produit_id) REFERENCES produits(id)
) DEFAULT CHARSET=utf8mb4;

